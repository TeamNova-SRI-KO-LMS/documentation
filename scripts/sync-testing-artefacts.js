#!/usr/bin/env node
/**
 * Import the generated artefacts from the testing repository.
 *
 *   npm run sync          copy them in
 *   npm run sync:check    fail if what is committed differs (used by CI)
 *
 * SENG 34213 §10.1 asks for the test register, the coverage report, the
 * performance results and the OWASP evidence to be submitted from
 * `documents/`. All four are *generated* — by `scripts/generate-test-register.js`
 * and friends in the testing repository — so the copies here are derived files
 * with a provenance banner, never hand-edited originals.
 *
 * `--check` exists because a stale copy is worse than a missing one: a
 * submitted PDF that claims a coverage figure the suite no longer produces is
 * a false statement about the product, and nobody notices until the viva.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const { REPO_ROOT, testingRepo } = require('./repo');

/**
 * What gets copied where.
 *
 * `links` rewrites relative Markdown links so they still resolve from the
 * destination. A copied document with dead links is a copied document nobody
 * follows.
 */
const MANIFEST = [
  {
    from: 'docs/testing/TEST_REGISTER.md',
    to: 'documents/testing/test-register.md',
    deliverable: '§10.1 #7 — Test Case Register',
    links: { './DEFECT_REGISTER.md': './defect-register.md' },
  },
  {
    from: 'docs/testing/DEFECT_REGISTER.md',
    to: 'documents/testing/defect-register.md',
    deliverable: '§6.5 — Defect register (supports §10.4 §6 "Limitations and known defects")',
    links: {},
  },
  {
    from: 'docs/testing/TRACEABILITY_MATRIX.md',
    to: 'documents/testing/traceability-matrix.md',
    deliverable: '§4.3 — Requirement-to-test traceability',
    links: { '../REQUIREMENTS_CATALOGUE.md': '../srs/srs-final.md' },
  },
  {
    from: 'docs/TEST_STRATEGY.md',
    to: 'documents/testing/test-strategy.md',
    deliverable: '§10.4 §5 — Testing strategy',
    links: {
      './testing/DEFECT_REGISTER.md': './defect-register.md',
      '../README.md': '../../README.md',
    },
  },
  {
    from: 'reports/coverage-summary.md',
    to: 'documents/testing/coverage-sprint8.md',
    deliverable: '§10.1 #6 — Test Coverage Report',
    links: {},
  },
  {
    from: 'reports/endpoint-coverage.md',
    to: 'documents/testing/endpoint-coverage.md',
    deliverable: '§6.4 — 100 % of API endpoints exercised',
    links: {},
  },
  {
    from: 'reports/performance-report.md',
    to: 'documents/testing/performance-report.md',
    deliverable: '§10.1 #9 — Performance Test Results',
    links: {},
    // k6 is a standalone binary and is not part of the default test run, so
    // this artefact may legitimately be absent on a developer machine. CI
    // always produces it (.github/workflows/performance.yml in the testing
    // repository), and the placeholder committed here says so plainly.
    optional: true,
  },
  {
    from: 'docs/security/OWASP_COMPLIANCE.md',
    to: 'documents/security/owasp-checklist.md',
    deliverable: '§10.1 #8 — OWASP Compliance Evidence',
    links: {
      '../testing/DEFECT_REGISTER.md': '../testing/defect-register.md',
      '../testing/TEST_REGISTER.md': '../testing/test-register.md',
    },
  },
];

const BANNER_START = '<!-- SYNCED-ARTEFACT:START -->';
const BANNER_END = '<!-- SYNCED-ARTEFACT:END -->';

function banner(entry) {
  return [
    BANNER_START,
    '',
    '> **Generated artefact — do not edit this file.**',
    `> Copied by \`npm run sync\` from \`${entry.from}\` in the`,
    '> [testing repository](https://github.com/TeamNova-SRI-KO-LMS/testing).',
    `> Deliverable: ${entry.deliverable}.`,
    '>',
    '> Edit the generator, run the suite, then run `npm run sync` again. Editing',
    '> the copy makes the document disagree with the suite that produced it,',
    '> which is the one failure mode this file exists to prevent.',
    '',
    BANNER_END,
    '',
  ].join('\n');
}

function rewriteLinks(markdown, links) {
  return Object.entries(links).reduce(
    (text, [from, to]) => text.split(`](${from})`).join(`](${to})`),
    markdown,
  );
}

/** The exact bytes that should be on disk for one manifest entry. */
function render(entry, source) {
  return banner(entry) + rewriteLinks(source, entry.links);
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const source = testingRepo();

  const copied = [];
  const missing = [];
  const stale = [];

  for (const entry of MANIFEST) {
    const sourcePath = path.join(source, entry.from);
    const targetPath = path.join(REPO_ROOT, entry.to);

    if (!fs.existsSync(sourcePath)) {
      missing.push(entry);
      continue;
    }

    const desired = render(entry, fs.readFileSync(sourcePath, 'utf8'));
    const current = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : null;

    if (current === desired) continue;

    if (checkOnly) {
      stale.push({ entry, reason: current === null ? 'not committed' : 'differs from source' });
      continue;
    }

    fs.mkdirSync(path.dirname(targetPath), { recursive: true });
    fs.writeFileSync(targetPath, desired);
    copied.push(entry);
  }

  process.stdout.write(`\n  Testing repository: ${source}\n\n`);

  for (const entry of MANIFEST) {
    const isMissing = missing.includes(entry);
    const isStale = stale.some((item) => item.entry === entry);
    const wasCopied = copied.includes(entry);

    let mark = '·';
    if (isMissing) mark = entry.optional ? '–' : '✗';
    else if (isStale) mark = '✗';
    else if (wasCopied) mark = '✓';

    process.stdout.write(`  ${mark} ${entry.to}\n`);
  }

  const required = missing.filter((entry) => !entry.optional);
  const optional = missing.filter((entry) => entry.optional);

  if (optional.length > 0) {
    process.stdout.write(
      [
        '',
        '  Not produced yet (optional locally, required in CI):',
        ...optional.map((entry) => `    ${entry.from}`),
        '',
        '  Produce it with:  cd <testing repo> && npm run test:perf',
        '  k6 must be installed — see the testing repository README.',
      ].join('\n') + '\n',
    );
  }

  if (required.length > 0) {
    process.stderr.write(
      [
        '',
        '  ✗ Missing generated artefacts:',
        ...required.map((entry) => `    ${entry.from}`),
        '',
        '  Produce them with:  cd <testing repo> && npm run coverage && npm run report:all',
        '',
      ].join('\n'),
    );
    process.exit(1);
  }

  if (stale.length > 0) {
    process.stderr.write(
      [
        '',
        '  ✗ These committed copies are out of date:',
        ...stale.map((item) => `    ${item.entry.to}  (${item.reason})`),
        '',
        '  Run:  npm run sync',
        '',
      ].join('\n'),
    );
    process.exit(1);
  }

  process.stdout.write(
    checkOnly
      ? '\n  ✓ Every synced artefact matches its source.\n\n'
      : `\n  ✓ ${copied.length} updated, ${MANIFEST.length - copied.length - missing.length} already current.\n\n`,
  );
}

main();
